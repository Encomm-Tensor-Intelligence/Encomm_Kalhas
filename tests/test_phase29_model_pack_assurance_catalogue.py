def test_maturity_is_evidence_derived_and_not_inflatable() -> None:
    assert _pan().maturity == "experimental"
    assert _fixture().maturity == "conformance_only"
    allowed_kinds = {"deterministic_execution", "synthetic_conformance"}
    for profile in (_pan(), _fixture()):
        assert {record.kind for record in profile.evidence} <= allowed_kinds
    assert {record.kind for record in _fixture().evidence} == {"synthetic_conformance"}
    inflated = _pan().model_dump(mode="json")
    inflated["maturity"] = "benchmarked"
    with pytest.raises(ValidationError):
        ModelPackAssuranceProfile.model_validate(inflated)
    inflated_fixture = _fixture().model_dump(mode="json")
    inflated_fixture["maturity"] = "experimental"
    with pytest.raises(ValidationError):
        ModelPackAssuranceProfile.model_validate(inflated_fixture)


