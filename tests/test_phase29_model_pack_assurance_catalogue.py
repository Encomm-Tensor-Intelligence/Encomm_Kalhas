"""H29-S09A tests for the Model Pack assurance profiles and portfolio catalogue.

The artifacts under ``model_packs/v1/`` are declarative data generated by
``scripts/export_model_pack_artifacts.py`` from the live pack release
profiles and the exact bytes of the named evidence modules. These tests
prove they are current, valid v1 contracts, bound to the exact live
release identities, backed by existing evidence, truthfully labeled, and
not wired into any runtime surface.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest
from kalhas.application.hashing import canonical_json, sha256_hex
from kalhas.contracts.v1.model_pack import (
    ModelPackAssuranceProfile,
    ModelPackCatalogueEntry,
    ModelPackReleaseProfile,
)
from pydantic import BaseModel, ValidationError

REPO_ROOT = Path(__file__).resolve().parents[1]
KALHAS_ROOT = REPO_ROOT / "kalhas"
ARTIFACT_DIR = REPO_ROOT / "model_packs" / "v1"
SCRIPT_PATH = REPO_ROOT / "scripts" / "export_model_pack_artifacts.py"
THIS_MODULE = "tests/test_phase29_model_pack_assurance_catalogue.py"

PAN_PATH = ARTIFACT_DIR / "assurance" / "kalhas-pan-0.1.0.json"
FIXTURE_PATH = ARTIFACT_DIR / "assurance" / "kalhas-conformance-stockflow-0.1.0.json"
CATALOGUE_PATH = ARTIFACT_DIR / "catalogue.json"

EXPECTED_PACK_IDS = (
    "kalhas-pan",
    "kalhas-maritime-trade",
    "kalhas-quantum-readiness",
    "kalhas-climate-civil",
    "kalhas-energy-sec",
    "kalhas-food-water",
    "kalhas-cyber-digital",
    "kalhas-critical-resilience",
    "kalhas-macro-fiscal",
    "kalhas-demography-capacity",
    "kalhas-geo-policy",
    "kalhas-robotics",
    "kalhas-neuro-symbolic",
)

FORBIDDEN_LABELS = (
    "government_ready",
    "certified",
    "production_ready",
    "production-safe",
    "universally",
)


def _generator() -> ModuleType:
    """The generator module, loaded from its script path.

    The generator is the sanctioned reader of the live pack release
    profiles; the test obtains them through it, so no test module other
    than the approved importers couples to a concrete pack.
    """
    spec = importlib.util.spec_from_file_location("export_model_pack_artifacts", SCRIPT_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _live_release_profiles() -> dict[str, ModelPackReleaseProfile]:
    profiles = _generator().live_release_profiles()
    assert isinstance(profiles, dict)
    return profiles


def _load(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def _pan() -> ModelPackAssuranceProfile:
    return ModelPackAssuranceProfile.model_validate(_load(PAN_PATH))


def _fixture() -> ModelPackAssuranceProfile:
    return ModelPackAssuranceProfile.model_validate(_load(FIXTURE_PATH))


def _catalogue() -> list[ModelPackCatalogueEntry]:
    raw = _load(CATALOGUE_PATH)
    assert isinstance(raw, list)
    return [ModelPackCatalogueEntry.model_validate(item) for item in raw]


def _self_hash(model: BaseModel) -> str:
    dumped: dict[str, object] = model.model_dump(mode="json")
    del dumped["content_hash"]
    return sha256_hex(canonical_json(dumped))


