def test_artifacts_validate_and_hashes_recompute() -> None:
    for profile in (_pan(), _fixture()):
        assert type(profile) is ModelPackAssuranceProfile
        assert _self_hash(profile) == profile.content_hash
        assert profile.tenant_id == "kalhas-synthetic"
        assert profile.schema_version == "1.0.0"
        assert profile.declared_at.isoformat() == "2026-10-28T12:00:00+00:00"
    assert _pan().identifier == "assurance-profile-kalhas-pan-0-1-0"
    assert _fixture().identifier == "assurance-profile-kalhas-conformance-stockflow-0-1-0"
    for entry in _catalogue():
        assert type(entry) is ModelPackCatalogueEntry
        assert _self_hash(entry) == entry.content_hash
        assert entry.tenant_id == "kalhas-synthetic"
        assert entry.schema_version == "1.0.0"
        assert entry.identifier == f"catalogue-entry-{entry.pack_id}-0-1-0"
        assert entry.declared_at.isoformat() == "2026-10-28T12:00:00+00:00"


