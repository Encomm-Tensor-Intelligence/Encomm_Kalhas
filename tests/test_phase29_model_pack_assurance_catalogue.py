def test_catalogue_has_the_exact_thirteen_entries_in_order() -> None:
    entries = _catalogue()
    assert [entry.pack_id for entry in entries] == list(EXPECTED_PACK_IDS)
    assert len({entry.identifier for entry in entries}) == 13
    assert all(entry.pack_version == "0.1.0" for entry in entries)
    assert "kalhas-conformance-stockflow" not in {entry.pack_id for entry in entries}
    assert all("conformance" not in entry.pack_id for entry in entries)
    assert all(entry.summary.strip() for entry in entries)


def test_only_pan_is_bound_and_all_others_are_roadmap_entries() -> None:
    pan_release = _live_release_profiles()["kalhas-pan"]
    pan_assurance = _pan()
    waves = {"kalhas-pan": "29-35", "kalhas-maritime-trade": "34A-35"}
    for entry in _catalogue():
        assert entry.metadata == {"roadmap_wave": waves.get(entry.pack_id, "post-35")}
        if entry.pack_id == "kalhas-pan":
            assert entry.displayed_maturity == "experimental"
            assert entry.release_profile_id == pan_release.identifier
            assert entry.release_profile_content_hash == pan_release.content_hash
            assert entry.assurance_profile_id == pan_assurance.identifier
            assert entry.assurance_profile_content_hash == pan_assurance.content_hash
        else:
            assert entry.displayed_maturity == "catalogued"
            assert entry.release_profile_id is None
            assert entry.release_profile_content_hash is None
            assert entry.assurance_profile_id is None
            assert entry.assurance_profile_content_hash is None


