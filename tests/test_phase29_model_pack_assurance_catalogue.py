def test_artifacts_contain_no_forbidden_labels() -> None:
    for path in (PAN_PATH, FIXTURE_PATH, CATALOGUE_PATH):
        text = path.read_text(encoding="utf-8").lower()
        for label in FORBIDDEN_LABELS:
            assert label not in text, (path.name, label)
    for maturity in ("benchmarked", "externally_reviewed", "partner_evaluation_ready"):
        for path in (PAN_PATH, FIXTURE_PATH, CATALOGUE_PATH):
            assert maturity not in path.read_text(encoding="utf-8"), (path.name, maturity)


