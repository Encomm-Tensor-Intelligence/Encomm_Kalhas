def test_nothing_under_kalhas_references_the_artifacts_or_generator() -> None:
    pattern = re.compile(r"(model_packs|export_model_pack_artifacts)")
    offenders = [
        path.relative_to(KALHAS_ROOT).as_posix()
        for path in sorted(KALHAS_ROOT.rglob("*.py"))
        if pattern.search(path.read_text(encoding="utf-8"))
    ]
    assert offenders == []
