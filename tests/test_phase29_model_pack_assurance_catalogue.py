def test_generator_check_mode_passes() -> None:
    completed = subprocess.run(
        [sys.executable, str(SCRIPT_PATH), "--check"],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
        check=False,
    )
    assert completed.returncode == 0, completed.stdout + completed.stderr


def test_artifact_set_is_exactly_the_three_files() -> None:
    on_disk = sorted(
        path.relative_to(ARTIFACT_DIR).as_posix()
        for path in ARTIFACT_DIR.rglob("*")
        if path.is_file()
    )
    assert on_disk == [
        "assurance/kalhas-conformance-stockflow-0.1.0.json",
        "assurance/kalhas-pan-0.1.0.json",
        "catalogue.json",
    ]


def test_artifacts_are_lf_only_and_canonically_formatted() -> None:
    for path in (PAN_PATH, FIXTURE_PATH, CATALOGUE_PATH):
        raw = path.read_bytes()
        assert b"\r" not in raw
        assert raw.endswith(b"\n")
        text = raw.decode("utf-8")
        assert (
            text
            == json.dumps(json.loads(text), indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        )


