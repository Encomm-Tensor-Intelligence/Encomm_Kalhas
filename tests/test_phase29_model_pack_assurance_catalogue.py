def test_evidence_exists_and_hashes_the_current_file_bytes() -> None:
    for profile in (_pan(), _fixture()):
        assert profile.evidence
        for record in profile.evidence:
            path = REPO_ROOT / record.reference
            assert path.is_file(), record.reference
            assert hashlib.sha256(path.read_bytes()).hexdigest() == record.content_hash
            assert record.reference != THIS_MODULE
        for claim in profile.supported_claims:
            assert claim.evidence_ids


